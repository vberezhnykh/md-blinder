// Контракт прогресса NER-воркера. Общий модуль (только типы), чтобы воркер и
// клиент не описывали одну и ту же форму сообщения дважды и не разъезжались.

// Фазы работы воркера в порядке прохождения. Раньше «всё до первого чанка»
// схлопывалось в один стейдж 'load', и после «100%» интерфейс молчал десятки
// секунд (скачивание кончилось, а создание ONNX-сессии и прогрев — нет). Теперь
// у каждой фазы свой маркер, чтобы было видно, чем воркер занят.
export type NerStage = 'download' | 'init' | 'warmup' | 'detect'

export type ExecProviderName = 'webgpu' | 'wasm'

// Одна форма прогресса на все фазы: поля, не относящиеся к фазе, просто пусты.
// Дискриминированный юнион пришлось бы протаскивать через три слоя
// (ner.ts → anonymize/index.ts → App.tsx) ради полей, которые в UI всё равно
// опциональны.
export interface NerProgress {
  stage: NerStage
  /** download: 0..100 */
  pct?: number
  /** download: модель взята из Cache Storage, сети не было */
  cached?: boolean
  /** init/warmup/detect: на чём реально считаем */
  ep?: ExecProviderName
  /** detect: сколько чанков уже посчитано / всего */
  chunk?: number
  chunks?: number
  /** detect: номер текущей партии / всего партий */
  batch?: number
  batches?: number
  /** detect: сколько чанков закроет текущая партия (маркер «сейчас считаю N») */
  batchChunks?: number
  /** миллисекунды с начала обработки этого запроса */
  elapsedMs?: number
}
