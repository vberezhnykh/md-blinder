// Языки OCR. Корпус — русские, украинские и английские договоры, часто
// двуязычные (кириллический текст + латинские названия компаний, SWIFT, IBAN),
// поэтому грузим все три модели сразу, а не угадываем язык документа.
//
// Почему это важно: eng-only OCR не падает на кириллице, а молча возвращает
// бессмысленную латиницу, которая дальше уходит в NER и в экспорт. Ошибки не
// видно нигде — виден только плохой результат детекции.
//
// rus и ukr нужны обе и не заменяют друг друга: в ukr.traineddata нет ы/ъ/э,
// в rus.traineddata нет і/ї/є/ґ. rus стоит первым как основной язык корпуса —
// Tesseract считает первый язык списка primary.
//
// Цена: распознавание с тремя языками медленнее, чем с одним (LSTM прогоняет
// слово по каждой модели и выбирает по confidence). Для сканов это приемлемо —
// этап NER всё равно на порядок дороже. Если станет узким местом, следующий
// шаг — распознать первую страницу всеми тремя и через worker.reinitialize()
// сузить список до победившего языка (+eng).
//
// Живёт отдельным модулем, а не внутри ocrPdf.ts, чтобы юнит-тест не тянул
// pdfjs-dist (он требует DOM и не импортируется в node-окружении vitest).
export const OCR_LANGS = ['rus', 'ukr', 'eng'] as const
